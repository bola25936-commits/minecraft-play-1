export type DimensionId = 'overworld' | 'nether';

export type BlockType =
  | 'air'
  | 'grass'
  | 'dirt'
  | 'stone'
  | 'obsidian'
  | 'netherrack'
  | 'nether_bricks'
  | 'glowstone'
  | 'soul_sand'
  | 'quartz_ore'
  | 'lava'
  | 'nether_portal';

export type ItemType = BlockType | 'flint_and_steel';

export type ArmorSlotKey = 'helmet' | 'chestplate' | 'leggings' | 'boots';
export const ARMOR_SLOT_KEYS: ArmorSlotKey[] = ['helmet', 'chestplate', 'leggings', 'boots'];

export type ToolKind = 'none' | 'pickaxe' | 'axe' | 'shovel';
export type SoundCategory = 'grass' | 'dirt' | 'stone' | 'wood' | 'sand' | 'glass' | 'leaves';

export interface BlockDef {
  id: BlockId;
  name: string;
  isBlock: boolean;
  solid: boolean;
  transparent: boolean;
  liquid?: boolean;
  hardness: number; // seconds with bare hand; -1 = unbreakable
  preferredTool: ToolKind;
  minTier?: number; // 0 = hand, 1 = wood, 2 = stone, 3 = iron, 4 = diamond
  dropId?: BlockId;
  dropCount?: number;
  lightLevel?: number;
  sound: SoundCategory;
  stackMax: number;
  // Tile indices in the 8x8 texture atlas (0..63)
  texTop?: number;
  texSide?: number;
  texBottom?: number;
  // Item properties
  toolType?: 'pickaxe' | 'sword' | 'axe' | 'shovel';
  toolTier?: number; // 1=wood, 2=stone, 3=iron, 4=diamond
  miningSpeed?: number;
  attackDamage?: number;
  foodRestore?: number;
  armorSlot?: ArmorSlotKey;
  armorDefense?: number;
}

